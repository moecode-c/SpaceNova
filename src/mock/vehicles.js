/** The designs an engineer finds already saved. */
export function buildVehicleDesigns(now = new Date()) {
  return DESIGN_SEED.map((design, i) => ({
    ...design,
    stack: design.stack.map((entry, j) => ({ ...entry, slotId: `${design.id}-slot-${j}` })),
    createdAt: new Date(now.getTime() - (30 - i * 9) * 86400000).toISOString(),
    updatedAt: new Date(now.getTime() - (2 + i * 3) * 86400000).toISOString(),
  }));
}
