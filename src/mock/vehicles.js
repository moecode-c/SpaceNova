export const COMPONENTS_BY_ID = new Map(COMPONENTS.map((c) => [c.id, c]));

/**
 * Resolve a saved design's stack into full component records.
 *
 * A design stores component ids and counts, not copies, so correcting a figure
 * in the library above corrects every design that uses that part.
 */
export function resolveStack(stack = []) {
  return stack
    .map((entry, i) => {
      const component = COMPONENTS_BY_ID.get(entry.componentId);
      if (!component) return null;
      return {
        ...component,
        slotId: entry.slotId ?? `slot-${i}`,
        count: Math.max(1, Math.round(entry.count ?? 1)),
      };
    })
    .filter(Boolean);
}

